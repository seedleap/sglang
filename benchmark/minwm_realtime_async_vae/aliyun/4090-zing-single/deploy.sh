#!/usr/bin/env bash
set -Eeuo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ROOT="$(git -C "${SCRIPT_DIR}" rev-parse --show-toplevel)"

RELEASED_PUBLIC_WEB_HOST="116.62.150.115"
SSH_HOST="${SSH_HOST:?set SSH_HOST=root@<new-aliyun-host> before deploying}"
REMOTE_DIR="${REMOTE_DIR:-/root/zing-realtime}"
REMOTE_SCRIPT="${REMOTE_SCRIPT:-${REMOTE_DIR}/start_remote.sh}"
REMOTE_OVERLAY="${REMOTE_OVERLAY:-${REMOTE_DIR}/sglang-main-overlay.tar.gz}"
PUBLIC_WEB_HOST="${PUBLIC_WEB_HOST:-${SSH_HOST#*@}}"
PUBLIC_GATEWAY_PORT="${PUBLIC_GATEWAY_PORT:-18080}"
PUBLIC_GATEWAY_BASE_URL="${PUBLIC_GATEWAY_BASE_URL:-http://${PUBLIC_WEB_HOST}:${PUBLIC_GATEWAY_PORT}}"
START_GPU_WORKERS="${START_GPU_WORKERS:-true}"
SKIP_IMAGE_PULL="${SKIP_IMAGE_PULL:-false}"
DEPLOY_STRATEGY="${DEPLOY_STRATEGY:-rolling}"
ROLLING_DRAIN_TIMEOUT_S="${ROLLING_DRAIN_TIMEOUT_S:-120}"
ROLLING_IDLE_TIMEOUT_S="${ROLLING_IDLE_TIMEOUT_S:-180}"
ROLLING_POLL_INTERVAL_S="${ROLLING_POLL_INTERVAL_S:-2}"
ROLLING_RESTART_COORDINATOR="${ROLLING_RESTART_COORDINATOR:-false}"
ROLLING_RESTART_VAE="${ROLLING_RESTART_VAE:-true}"
ROLLING_RESTART_DENOISERS="${ROLLING_RESTART_DENOISERS:-true}"
ROLLING_RESTART_GATEWAY="${ROLLING_RESTART_GATEWAY:-true}"
ROLLING_RESTART_WEBUI="${ROLLING_RESTART_WEBUI:-true}"
ALIYUN_ECS_RAM_ROLE="${ALIYUN_ECS_RAM_ROLE:-ZingRealtimeEcsPullRole}"
DEFAULT_RUNTIME_IMAGE="${DEFAULT_RUNTIME_IMAGE:-829115578968.dkr.ecr.us-east-2.amazonaws.com/leap-world/minwm-runtime:minwm-r3-20260820}"
DENOISER_IMAGE="${DENOISER_IMAGE:-${DEFAULT_RUNTIME_IMAGE}}"
VAE_IMAGE="${VAE_IMAGE:-${DENOISER_IMAGE}}"
GATEWAY_IMAGE="${GATEWAY_IMAGE:-${DENOISER_IMAGE}}"
CONTROL_IMAGE="${CONTROL_IMAGE:-${DENOISER_IMAGE}}"
WEBUI_IMAGE="${WEBUI_IMAGE:-}"
AUTO_DERIVE_VAE_FFMPEG_IMAGE="${AUTO_DERIVE_VAE_FFMPEG_IMAGE:-true}"
VAE_FFMPEG_IMAGE="${VAE_FFMPEG_IMAGE:-}"
AWS_ECR_REGION="${AWS_ECR_REGION:-us-east-2}"
ECR_REGISTRY="${ECR_REGISTRY:-829115578968.dkr.ecr.us-east-2.amazonaws.com}"
SKIP_ECR_LOGIN="${SKIP_ECR_LOGIN:-false}"
DENOISER_START_MODE="${DENOISER_START_MODE:-profile}"
MINWM_PROFILE="${MINWM_PROFILE:-auto}"
PROFILE_MODEL_PATH="${PROFILE_MODEL_PATH:-/models/minwm-tianpeng-gap12}"
PROFILE_MODEL_HOST_DIR="${PROFILE_MODEL_HOST_DIR:-}"
PROFILE_MODEL_MOUNT_ENABLED="${PROFILE_MODEL_MOUNT_ENABLED:-true}"
PROFILE_TAEHV_CHECKPOINT_PATH="${PROFILE_TAEHV_CHECKPOINT_PATH:-/models/taehv/taew2_2.pth}"
TAEHV_HOST_DIR="${TAEHV_HOST_DIR:-}"
TAEHV_HOST_CHECKPOINT_PATH="${TAEHV_HOST_CHECKPOINT_PATH:-}"
CONTAINER_PYTHONPATH="${CONTAINER_PYTHONPATH:-/opt/sglang/python}"
LEGACY_MODEL_CONTAINER_PATH="${LEGACY_MODEL_CONTAINER_PATH:-/work/model}"
LEGACY_TAEHV_CHECKPOINT_PATH="${LEGACY_TAEHV_CHECKPOINT_PATH:-/opt/taehv/taew2_2.pth}"
VAE_TAEHV_CHECKPOINT_PATH="${VAE_TAEHV_CHECKPOINT_PATH:-${PROFILE_TAEHV_CHECKPOINT_PATH}}"
DENOISER_ATTENTION_BACKEND="${DENOISER_ATTENTION_BACKEND:-fa}"
DENOISER_ATTENTION_IMPL="${DENOISER_ATTENTION_IMPL:-packed}"
DENOISER_CACHE_ROTATED_K="${DENOISER_CACHE_ROTATED_K:-false}"
DENOISER_PERFORMANCE_MODE="${DENOISER_PERFORMANCE_MODE:-speed}"
DENOISER_ENABLE_CUDA_GRAPH="${DENOISER_ENABLE_CUDA_GRAPH:-false}"
DENOISER_PYTORCH_CUDA_ALLOC_CONF="${DENOISER_PYTORCH_CUDA_ALLOC_CONF:-expandable_segments:True}"
REALTIME_WORKER_MAX_CONSUMED_AGE_S="${REALTIME_WORKER_MAX_CONSUMED_AGE_S:-120}"
REALTIME_TARGET_FPS="${REALTIME_TARGET_FPS:-18}"
H264_LIVE_EDGE_TARGET_MS="${H264_LIVE_EDGE_TARGET_MS:-500}"
H264_LIVE_EDGE_SEEK_THRESHOLD_MS="${H264_LIVE_EDGE_SEEK_THRESHOLD_MS:-900}"
GATEWAY_OUTPUT_QUEUE_MAX_MESSAGES="${GATEWAY_OUTPUT_QUEUE_MAX_MESSAGES:-4096}"
GATEWAY_OUTPUT_QUEUE_MAX_BYTES="${GATEWAY_OUTPUT_QUEUE_MAX_BYTES:-67108864}"

log() {
  printf '[%s] %s\n' "$(date '+%Y-%m-%d %H:%M:%S')" "$*" >&2
}

image_uses_registry() {
  local registry="$1"
  local image
  for image in "${DENOISER_IMAGE}" "${VAE_IMAGE}" "${CONTROL_IMAGE}" "${GATEWAY_IMAGE}" "${WEBUI_IMAGE}"; do
    [[ -n "${image}" && "${image}" == "${registry}/"* ]] && return 0
  done
  return 1
}

login_remote_ecr_from_local() {
  if [[ "${SKIP_IMAGE_PULL}" == "true" || "${SKIP_ECR_LOGIN}" == "true" ]]; then
    return
  fi
  if ! image_uses_registry "${ECR_REGISTRY}"; then
    return
  fi
  if ! command -v aws >/dev/null 2>&1; then
    log "local aws CLI is unavailable; remote script will try ECR login"
    return
  fi

  log "refreshing remote Docker auth for ECR ${ECR_REGISTRY}"
  if ! aws ecr get-login-password --region "${AWS_ECR_REGION}" | \
    ssh -o BatchMode=yes "${SSH_HOST}" \
      "docker login --username AWS --password-stdin '${ECR_REGISTRY}' >/dev/null"; then
    log "local ECR login did not complete; remote script will try ECR login or existing Docker auth"
  fi
}

main() {
  if [[ "${SSH_HOST}" == *"${RELEASED_PUBLIC_WEB_HOST}"* || "${PUBLIC_WEB_HOST}" == "${RELEASED_PUBLIC_WEB_HOST}" ]]; then
    echo "${RELEASED_PUBLIC_WEB_HOST} was released; set SSH_HOST/PUBLIC_WEB_HOST to the new Aliyun host." >&2
    exit 1
  fi

  local archive
  archive="$(mktemp -t sglang-aliyun-overlay.XXXXXX.tar.gz)"
  trap "rm -f '${archive}'" EXIT

  log "packaging latest main-based realtime code overlay"
  COPYFILE_DISABLE=1 tar \
    --no-xattrs \
    --exclude='._*' \
    --exclude='.DS_Store' \
    -C "${ROOT}" \
    -czf "${archive}" \
    python/sglang/multimodal_gen

  log "uploading deployment artifacts to ${SSH_HOST}"
  ssh -o BatchMode=yes -o StrictHostKeyChecking=accept-new "${SSH_HOST}" \
    "mkdir -p '${REMOTE_DIR}'"
  scp -q -o BatchMode=yes "${archive}" "${SSH_HOST}:${REMOTE_OVERLAY}"
  scp -q -o BatchMode=yes "${SCRIPT_DIR}/start_remote.sh" \
    "${SSH_HOST}:${REMOTE_SCRIPT}"
  login_remote_ecr_from_local

  log "starting direct-H264 deployment"
  ssh -o BatchMode=yes "${SSH_HOST}" \
    "chmod +x '${REMOTE_SCRIPT}' && \
     CODE_OVERLAY_ARCHIVE='${REMOTE_OVERLAY}' \
     PUBLIC_WEB_HOST='${PUBLIC_WEB_HOST}' \
     PUBLIC_GATEWAY_PORT='${PUBLIC_GATEWAY_PORT}' \
     PUBLIC_GATEWAY_BASE_URL='${PUBLIC_GATEWAY_BASE_URL}' \
     START_GPU_WORKERS='${START_GPU_WORKERS}' \
     SKIP_IMAGE_PULL='${SKIP_IMAGE_PULL}' \
     DEPLOY_STRATEGY='${DEPLOY_STRATEGY}' \
     ROLLING_DRAIN_TIMEOUT_S='${ROLLING_DRAIN_TIMEOUT_S}' \
     ROLLING_IDLE_TIMEOUT_S='${ROLLING_IDLE_TIMEOUT_S}' \
     ROLLING_POLL_INTERVAL_S='${ROLLING_POLL_INTERVAL_S}' \
     ROLLING_RESTART_COORDINATOR='${ROLLING_RESTART_COORDINATOR}' \
     ROLLING_RESTART_VAE='${ROLLING_RESTART_VAE}' \
     ROLLING_RESTART_DENOISERS='${ROLLING_RESTART_DENOISERS}' \
     ROLLING_RESTART_GATEWAY='${ROLLING_RESTART_GATEWAY}' \
     ROLLING_RESTART_WEBUI='${ROLLING_RESTART_WEBUI}' \
     ALIYUN_ECS_RAM_ROLE='${ALIYUN_ECS_RAM_ROLE}' \
     DEFAULT_RUNTIME_IMAGE='${DEFAULT_RUNTIME_IMAGE}' \
     DENOISER_IMAGE='${DENOISER_IMAGE}' \
     VAE_IMAGE='${VAE_IMAGE}' \
     GATEWAY_IMAGE='${GATEWAY_IMAGE}' \
     CONTROL_IMAGE='${CONTROL_IMAGE}' \
     WEBUI_IMAGE='${WEBUI_IMAGE}' \
     AUTO_DERIVE_VAE_FFMPEG_IMAGE='${AUTO_DERIVE_VAE_FFMPEG_IMAGE}' \
     VAE_FFMPEG_IMAGE='${VAE_FFMPEG_IMAGE}' \
     AWS_ECR_REGION='${AWS_ECR_REGION}' \
     ECR_REGISTRY='${ECR_REGISTRY}' \
     SKIP_ECR_LOGIN='${SKIP_ECR_LOGIN}' \
     DENOISER_START_MODE='${DENOISER_START_MODE}' \
     MINWM_PROFILE='${MINWM_PROFILE}' \
     PROFILE_MODEL_PATH='${PROFILE_MODEL_PATH}' \
     PROFILE_MODEL_HOST_DIR='${PROFILE_MODEL_HOST_DIR}' \
     PROFILE_MODEL_MOUNT_ENABLED='${PROFILE_MODEL_MOUNT_ENABLED}' \
     PROFILE_TAEHV_CHECKPOINT_PATH='${PROFILE_TAEHV_CHECKPOINT_PATH}' \
     TAEHV_HOST_DIR='${TAEHV_HOST_DIR}' \
     TAEHV_HOST_CHECKPOINT_PATH='${TAEHV_HOST_CHECKPOINT_PATH}' \
     CONTAINER_PYTHONPATH='${CONTAINER_PYTHONPATH}' \
     LEGACY_MODEL_CONTAINER_PATH='${LEGACY_MODEL_CONTAINER_PATH}' \
     LEGACY_TAEHV_CHECKPOINT_PATH='${LEGACY_TAEHV_CHECKPOINT_PATH}' \
     VAE_TAEHV_CHECKPOINT_PATH='${VAE_TAEHV_CHECKPOINT_PATH}' \
     DENOISER_ATTENTION_BACKEND='${DENOISER_ATTENTION_BACKEND}' \
     DENOISER_ATTENTION_IMPL='${DENOISER_ATTENTION_IMPL}' \
     DENOISER_CACHE_ROTATED_K='${DENOISER_CACHE_ROTATED_K}' \
     DENOISER_PERFORMANCE_MODE='${DENOISER_PERFORMANCE_MODE}' \
     DENOISER_ENABLE_CUDA_GRAPH='${DENOISER_ENABLE_CUDA_GRAPH}' \
     DENOISER_PYTORCH_CUDA_ALLOC_CONF='${DENOISER_PYTORCH_CUDA_ALLOC_CONF}' \
     REALTIME_WORKER_MAX_CONSUMED_AGE_S='${REALTIME_WORKER_MAX_CONSUMED_AGE_S}' \
     REALTIME_TARGET_FPS='${REALTIME_TARGET_FPS}' \
     H264_LIVE_EDGE_TARGET_MS='${H264_LIVE_EDGE_TARGET_MS}' \
     H264_LIVE_EDGE_SEEK_THRESHOLD_MS='${H264_LIVE_EDGE_SEEK_THRESHOLD_MS}' \
     GATEWAY_OUTPUT_QUEUE_MAX_MESSAGES='${GATEWAY_OUTPUT_QUEUE_MAX_MESSAGES}' \
     GATEWAY_OUTPUT_QUEUE_MAX_BYTES='${GATEWAY_OUTPUT_QUEUE_MAX_BYTES}' \
     exec '${REMOTE_SCRIPT}'"

  log "WebUI: http://${PUBLIC_WEB_HOST}/?mode=i2v&playback=smooth_timeline"
  log "Gateway: ${PUBLIC_GATEWAY_BASE_URL}"
}

main "$@"
